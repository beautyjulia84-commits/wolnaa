import assert from 'node:assert/strict';
import {ageAt,validateConsent,signatureValid,type ConsentInput} from '../lib/muttizettel';
const event={id:'test',date:'2026-11-06',time:'22:00',min_age:16,title:'Testveranstaltung'};
const person={name:'Alex Beispiel',address:'Musterstraße 12, 80331 München',phone:'+49 123 456789',birthDate:'2009-11-06'};
const data:ConsentInput={eventId:'test',minor:person,parent:{...person,name:'Maria Beispiel'},companion:{...person,name:'Erik Beispiel',birthDate:'2000-01-01'},mode:'print',parentSignature:[],companionSignature:[],parentAgrees:false,companionAgrees:false,reviewed:true};
const now=Date.parse('2026-10-24');
assert.equal(validateConsent(data,event,now),'');
assert.equal(ageAt('2010-11-06',event.date),16);
assert.equal(ageAt('2008-11-06',event.date),18);
assert.ok(Number.isNaN(ageAt('2009-02-29',event.date)));
for(const birthDate of ['2011-11-06','2008-11-06'])assert.notEqual(validateConsent({...data,minor:{...person,birthDate}},event,now),'');
assert.notEqual(validateConsent({...data,companion:{...person,name:'Erik Beispiel'}},event,now),'');
assert.notEqual(validateConsent(data,{...event,min_age:18},now),'');
assert.notEqual(validateConsent(data,{...event,description:'ABGESAGT'},now),'');
assert.notEqual(validateConsent(data,event,Date.parse('2026-12-01')),'');
assert.notEqual(validateConsent({...data,reviewed:false},event,now),'');
assert.notEqual(validateConsent({...data,mode:'digital'},event,now),'');
const signature=[[{x:.1,y:.5},{x:.3,y:.2},{x:.5,y:.7}]];
assert.equal(signatureValid(signature),true);
assert.equal(signatureValid([[{x:NaN,y:0}]]),false);
assert.equal(signatureValid([[{x:2,y:0}]]),false);
assert.equal(signatureValid([Array.from({length:4001},(_,i)=>({x:(i%2)/2,y:.5}))]),false);
assert.equal(validateConsent({...data,mode:'digital',parentSignature:signature,companionSignature:signature,parentAgrees:true,companionAgrees:true},event,now),'');
console.log('Muttizettel: validation passed');
