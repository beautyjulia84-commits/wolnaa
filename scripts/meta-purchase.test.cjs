const assert=require('node:assert/strict');
const fs=require('node:fs');
const ts=require('typescript');
const Module=require('node:module');
const m=new Module('/tmp/meta-purchase-unit.cjs',module);
m.filename='/tmp/meta-purchase-unit.cjs';
m._compile(ts.transpileModule(fs.readFileSync('lib/meta-purchase.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,m.filename);
const {metaCheckoutMetadata,buildMetaPurchase}=m.exports;
const req=cookie=>new Request('https://www.wolnaa.de/api/create-checkout-session',{headers:{cookie,'user-agent':'Test browser'}});
assert.deepEqual(metaCheckoutMetadata(req('_fbp=fb.1.1793000000000.123')),{});
assert.deepEqual(metaCheckoutMetadata(req('wolnaa-meta-consent=1; _fbp=fb.1.1793000000000.123')),{});
assert.deepEqual(metaCheckoutMetadata(req('wolnaa-meta-consent=2; _fbp=invalid')),{});
const meta=metaCheckoutMetadata(req('wolnaa-meta-consent=2; _fbp=fb.1.1793000000000.123; _fbc=fb.1.1793000000000.click_id'));
assert.equal(meta.metaConsent,'2');
const session={id:'cs_live_test_unit_only',livemode:true,mode:'payment',payment_status:'paid',amount_total:2400,currency:'eur',metadata:{...meta,metaTicketCount:'2',customerName:'Do not transmit',customerEmail:'private@example.test'}};
const event=buildMetaPurchase(session,1793000000);
assert.equal(event.custom_data.value,24);
assert.equal(event.custom_data.num_items,2);
assert.equal(event.custom_data.currency,'EUR');
assert.equal(event.event_source_url,'https://www.wolnaa.de/success');
assert.equal(event.event_id,buildMetaPurchase(session,1793000001).event_id);
assert.notEqual(event.event_id,buildMetaPurchase({...session,id:'another'},1793000000).event_id);
assert.ok(!JSON.stringify(event).includes('Do not transmit'));
assert.ok(!JSON.stringify(event).includes('private@example.test'));
assert.ok(!JSON.stringify(event).includes('cs_live_'));
for(const patch of [{livemode:false},{payment_status:'unpaid'},{payment_status:'no_payment_required'},{amount_total:0},{mode:'subscription'},{metadata:{}},{metadata:{...meta,metaTicketCount:'0'}},{metadata:{...meta,metaTicketCount:'2',metaUserAgent:''}}]) assert.equal(buildMetaPurchase({...session,...patch},1793000000),null);
console.log('Meta purchase tests passed: consent, paid/live gate, amount, ticket count, privacy and stable deduplication.');
