import assert from 'node:assert/strict';
import {berlinInstant,berlinLocal,defaultEndLocal,eventTiming,validateSchedule} from '../lib/event-timing.ts';
assert.equal(berlinInstant('2026-10-02T19:00'),'2026-10-02T17:00:00.000Z');
assert.equal(berlinInstant('2026-12-02T19:00'),'2026-12-02T18:00:00.000Z');
assert.equal(berlinLocal('2026-10-02T17:00:00Z'),'2026-10-02T19:00');
assert.throws(()=>berlinInstant('2026-03-29T02:30'));
assert.throws(()=>berlinInstant('2026-02-30T19:00'));
assert.equal(berlinInstant('2026-10-25T02:30'),'2026-10-25T00:30:00.000Z');
assert.equal(defaultEndLocal('2026-12-31'),'2027-01-01T05:00');
const event={date:'2026-10-02',time:'20:00',online_sale_ends_at:berlinInstant('2026-10-02T19:00'),event_ends_at:berlinInstant('2026-10-03T05:00')};
const at = t=>eventTiming(event,Date.parse(berlinInstant(t)));
assert.equal(at('2026-10-02T18:59').salesClosed,false);
assert.equal(at('2026-10-02T19:00').salesClosed,true);
assert.equal(at('2026-10-02T19:00').ended,false);
assert.equal(at('2026-10-02T20:00').status,'Läuft');
assert.equal(at('2026-10-03T04:59').ended,false);
assert.equal(at('2026-10-03T05:00').ended,true);
assert.equal(at('2026-10-03T05:00').status,'Abgeschlossen');
assert.equal(eventTiming({...event,online_sale_ends_at:null},Date.parse(berlinInstant('2026-10-02T20:00'))).salesClosed,true);
assert.equal(eventTiming({...event,event_ends_at:null},Date.parse(berlinInstant('2026-10-03T05:00'))).ended,true);
assert.equal(eventTiming({date:'broken'}).salesClosed,true);
assert.throws(()=>validateSchedule({date:'2026-10-02',time:'20:00',eventEndsAt:'2026-10-02T05:00'}));
assert.throws(()=>validateSchedule({date:'2026-10-02',time:'20:00',onlineSaleEndsAt:'2026-10-03T06:00'}));
console.log('Event timing: cutoff, end, German time, DST and invalid configuration passed.');
